export function parseWordPack(text: string, prefix: string, topic: string, level: BankWord['level']): BankWord[] {
  const out: BankWord[] = [];
  String(text || '').split('\n').forEach((ln, i) => {
    const c = ln.split('|').map(x => x.trim());
    if (c.length < 2 || !c[0] || !c[1]) return;
    out.push({ id: `${prefix}_${i}_${c[0].toLowerCase().replace(/[^a-z0-9]+/g, '')}`.slice(0, 60), en: c[0], uz: c[1], ex: c[2] || '', exUz: c[3] || '', ipa: '', pos: '', col: [], fam: [], hook: '', track: 'acad', topic, level, order: i });
  });
  return out;
}

export interface GrammarRow { title: string; formula: string; text: string; ex: string }
export function parseGrammar(text: string): GrammarRow[] {
  return String(text || '').split('\n').map(l => l.split('|').map(x => x.trim())).filter(c => c.length >= 3 && c[0]).map(c => ({ title: c[0], formula: c[1] || '', text: c[2] || '', ex: c[3] || '' }));
}
